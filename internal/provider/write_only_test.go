	resource.Test(t, resource.TestCase{
		ProtoV6ProviderFactories: testAccProtoV6ProviderFactories,
		Steps: []resource.TestStep{{
			Config: `
provider "sdwan" {
  url      = "https://127.0.0.1:1"
  username = "dummy"
  password = "dummy"
}

resource "sdwan_other_trustsec_feature" "test" {
  name                       = "write_only_test"
  feature_profile_id         = "f6dd22c8-0b4f-496c-9a0b-6813d1f8b8ac"
  device_password_wo         = "cisco123"
  device_password_wo_version = 1
}
`,
			PlanOnly: true,
			// A valid write-only configuration produces no validation diagnostic, so the
			// run proceeds past ValidateResourceConfig and stops at provider configuration,
			// which eagerly authenticates against the (unreachable) Manager. Matching that
			// client error — and not any "Invalid Attribute Combination" / "Missing
			// Required Attribute" diagnostic — proves ValidateConfig accepted the config.
			ExpectError: regexp.MustCompile("Unable to create client"),
		}},
	})
